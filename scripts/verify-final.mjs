import puppeteer from 'puppeteer';
import fs from 'node:fs';
const URL=process.env.URL||'http://localhost:4173/?quality=low';
const OUT='verify'; fs.mkdirSync(OUT,{recursive:true});
const browser=await puppeteer.launch({headless:true,args:['--no-sandbox','--disable-setuid-sandbox','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader','--window-size=1440,860']});
const page=await browser.newPage(); await page.setViewport({width:1440,height:860});
const errors=[]; page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
page.on('pageerror',e=>errors.push('pageerror: '+e.message));
await page.goto(URL,{waitUntil:'domcontentloaded',timeout:60000});
await page.waitForFunction('window.__YUNSEUL__ && window.__YUNSEUL__.loaded===true',{timeout:150000});
await new Promise(r=>setTimeout(r,4000));
const shot=async n=>{await page.screenshot({path:`${OUT}/${n}.png`});return n;};
const R={};
R.spawn=await shot('f01-spawn');
R.wheel=await page.evaluate(async()=>{const {player}=window.__YUNSEUL__;const c=document.querySelector('canvas');
 for(let i=0;i<40;i++)c.dispatchEvent(new WheelEvent('wheel',{deltaY:-120,bubbles:true,cancelable:true}));
 await new Promise(r=>setTimeout(r,250));return {pitchDeg:+(player.pitch*180/Math.PI).toFixed(1),fov:player.camera.fov};});
await new Promise(r=>setTimeout(r,600)); R.sky=await shot('f02-sky');
R.wheelDown=await page.evaluate(async()=>{const {player}=window.__YUNSEUL__;const c=document.querySelector('canvas');
 for(let i=0;i<80;i++)c.dispatchEvent(new WheelEvent('wheel',{deltaY:120,bubbles:true,cancelable:true}));
 await new Promise(r=>setTimeout(r,250));return {pitchDeg:+(player.pitch*180/Math.PI).toFixed(1)};});
await new Promise(r=>setTimeout(r,600)); R.ground=await shot('f03-ground');
R.roof=await page.evaluate(async()=>{const {player,streamer}=window.__YUNSEUL__;
 player.setPlatforms(streamer.getPlatforms());
 player.position.set(-963,42.89+1.7,-108); player.yaw=-1.45; player.pitch=-0.10;
 player.velocity.set(0,0,0);player.onGround=true;player.update(0);
 streamer.requestAround(-963,-108); await new Promise(r=>setTimeout(r,3000));
 return {eyeY:+player.position.y.toFixed(2),standingOn:+player.getGroundHeight().toFixed(2),
  platforms:streamer.getPlatforms().length};});
await new Promise(r=>setTimeout(r,1200)); R.roofShot=await shot('f04-arts-center-roof');
R.sculpture=await page.evaluate(async()=>{const {player,streamer}=window.__YUNSEUL__;
 const list=streamer.sculptures||[]; if(!list.length)return {count:0};
 const t=list.find(s=>s.kind==='horn')||list.find(s=>s.kind==='totem')||list[0];
 player.position.set(t.x+7,1.7,t.z+7);
 player.yaw=Math.atan2(-(t.x-(t.x+7)),-(t.z-(t.z+7))); player.pitch=0.10; player.update(0);
 streamer.requestAround(t.x,t.z); await new Promise(r=>setTimeout(r,2500));
 return {count:list.length,kinds:[...new Set(list.map(s=>s.kind))],target:t};});
await new Promise(r=>setTimeout(r,1000)); R.sculptureShot=await shot('f05-sculpture');
R.bridge=await page.evaluate(async()=>{const {player,streamer}=window.__YUNSEUL__;
 const d=await fetch('data/incheon-bridge.json').then(r=>r.json()); const p=d.pylons[0];
 const x=p.x+560,z=p.z+470;
 player.position.set(x,1.7,z);player.yaw=Math.atan2(-(p.x-x),-(p.z-z));player.pitch=0.16;player.update(0);
 streamer.requestAround(x,z); await new Promise(r=>setTimeout(r,2500));
 return {pylon:p,mastHeight:d.mastHeight,from:{x:Math.round(x),z:Math.round(z)}};});
await new Promise(r=>setTimeout(r,1000)); R.bridgeShot=await shot('f06-bridge');
R.stats=await page.evaluate(()=>{const {streamer,renderer}=window.__YUNSEUL__;
 return {stats:streamer.stats,sculptures:(streamer.sculptures||[]).length,
  platforms:streamer.getPlatforms().length,calls:renderer.info.render.calls};});
R.errors=errors.slice(0,10);
fs.writeFileSync(`${OUT}/final-report.json`,JSON.stringify(R,null,2));
console.log(JSON.stringify(R,null,2));
await browser.close();
